#!/usr/bin/env node
/**
 * Generates docs/feature-flag-inventory.md from the sources of truth for flag defaults:
 *   - server/config/feature-flags.yaml            seed value and description
 *   - FAIL_CLOSED_FLAGS (entitlementService.ts)  missing-row behavior
 *   - COHORT_FEATURES (featureCohorts.ts)        whether Admin can set a user cohort
 *
 *   node scripts/generate-flag-inventory.mjs          write the inventory
 *   node scripts/generate-flag-inventory.mjs --check  exit 1 if the inventory is stale
 *
 * Seed values are defaults only. Live values are in the database (Admin -> Feature Flags).
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const YAML_PATH = path.join(root, 'server/config/feature-flags.yaml');
const ENTITLEMENT_PATH = path.join(root, 'server/src/services/entitlementService.ts');
const COHORT_PATH = path.join(root, 'server/src/services/featureCohorts.ts');
const OUT = path.join(root, 'docs/feature-flag-inventory.md');

const normalize = (text) => text.replace(/\r\n/g, '\n');

/** Extracts quoted keys from the first `<name> = new Set([...])` or `<name> = [...]` literal. */
const extractKeys = (source, name) => {
  const match = new RegExp(`${name}\\s*=\\s*(?:new Set\\()?\\[([\\s\\S]*?)\\]`).exec(source);
  if (!match) throw new Error(`Could not find ${name}`);
  const body = match[1].replace(/\/\/.*$/gm, '');
  return new Set([...body.matchAll(/'([a-z0-9_]+)'/g)].map((m) => m[1]));
};

const AREAS = [
  ['Planning, maps and discovery', /^(planning_|trip_day_map|trip_bundle|getyourguide_|stays_|attractions_)/],
  ['Imports and ingestion', /^(feature_ingest_|ingest|flight_parser|parser_|itinerary_document_import)/],
  ['Notifications', /^notifications_/],
  ['Trip blog', /^trip_blog_/],
  ['Itinerary generation', /^(itinerary_|ai_)/],
  ['Expenses and billing', /^(expense_|premium|receipt_|cost_|csv_|merchant_)/],
  ['Analytics, privacy and diagnostics', /^(analytics_|diagnostics_|age_gate)/],
];
const areaOf = (key) => AREAS.find(([, re]) => re.test(key))?.[0] ?? 'Core and other';

const cell = (text) => String(text ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

const build = () => {
  const yaml = parse(readFileSync(YAML_PATH, 'utf8')) ?? {};
  const flags = yaml.flags ?? {};
  const failClosed = extractKeys(readFileSync(ENTITLEMENT_PATH, 'utf8'), 'FAIL_CLOSED_FLAGS');
  const cohorts = extractKeys(readFileSync(COHORT_PATH, 'utf8'), 'COHORT_FEATURES');

  const rows = new Map();
  for (const [key, raw] of Object.entries(flags)) {
    const enabled = typeof raw === 'object' && raw !== null && typeof raw.enabled === 'boolean' ? raw.enabled : true;
    rows.set(key, { key, seed: enabled ? 'on' : 'off', description: raw?.description ?? '' });
  }
  for (const key of failClosed) {
    if (!rows.has(key)) rows.set(key, { key, seed: 'not seeded', description: 'Read by code but has no YAML seed; missing row means off.' });
  }

  const missingRow = (key) => (failClosed.has(key) || key.startsWith('expense_import_plaid') ? '**off**' : 'on');
  const grouped = new Map();
  for (const row of [...rows.values()].sort((a, b) => a.key.localeCompare(b.key))) {
    const area = areaOf(row.key);
    if (!grouped.has(area)) grouped.set(area, []);
    grouped.get(area).push(row);
  }

  const order = [...AREAS.map(([name]) => name), 'Core and other'].filter((name) => grouped.has(name));
  const lines = [
    '# Feature flag inventory',
    '',
    '<!-- Generated by `npm run docs:flags` (scripts/generate-flag-inventory.mjs). Do not edit by hand. -->',
    '',
    '[README](../README.md) · [Feature flag guide](feature-flags.md) · [Feature activation](operations/feature-activation.md) · [Manual administration](operations/manual-administration.md#enable-or-disable-a-feature)',
    '',
    `Every flag seeded in \`server/config/feature-flags.yaml\` (${rows.size} in total), generated from source. **Seed values are defaults only**: they create missing database rows at startup and never overwrite a live value. Check the live value in Admin → Feature Flags.`,
    '',
    '- **Seed:** the value a new deployment starts with.',
    '- **Missing row:** what the server does if the database has no row for the flag. **off** means fail-closed (`FAIL_CLOSED_FLAGS` in `entitlementService.ts`, or the Plaid family\'s own check).',
    '- **Cohort:** Admin can restrict the flag to listed users (`COHORT_FEATURES` in `featureCohorts.ts`).',
    '',
    '## Contents',
    '',
    ...order.map((area) => `- [${area}](#${area.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-')}) (${grouped.get(area).length})`),
    '',
  ];
  for (const area of order) {
    lines.push(`## ${area}`, '', '| Flag | Seed | Missing row | Cohort | Description |', '|---|---|---|---|---|');
    for (const row of grouped.get(area)) {
      lines.push(`| \`${row.key}\` | ${row.seed} | ${missingRow(row.key)} | ${cohorts.has(row.key) ? 'yes' : ''} | ${cell(row.description)} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
};

const output = build();
if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? normalize(readFileSync(OUT, 'utf8')) : '';
  if (current !== output) {
    console.error('docs/feature-flag-inventory.md is stale. Run: npm run docs:flags');
    process.exit(1);
  }
  console.log('docs/feature-flag-inventory.md is up to date.');
} else {
  writeFileSync(OUT, output, 'utf8');
  console.log(`Wrote ${path.relative(root, OUT)}`);
}
